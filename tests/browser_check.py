    for _ in range(100):
        if process.poll() is not None:raise RuntimeError('Testserver is onverwacht gestopt')
        try:
            urllib.request.urlopen(BASE+'/api/health',timeout=1)
            return process
        except Exception:time.sleep(.1)
    raise RuntimeError('Testserver kon niet starten')

